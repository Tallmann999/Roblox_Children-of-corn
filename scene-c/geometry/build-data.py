"""Build Scene C's immutable neutral Luau data from the read-only FBX intake.

No Blender, asset upload, source FBX edit, or A/B data is involved. The orthogonal
axis conversion is right-handed and every asset uses the same uniform scale.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
INTAKE = ROOT / ".artifacts/scene-C/2026-10-22-intake/mesh-arrays.json"
OUT = ROOT / "scene-c/data"
KEYS = {
    "SM_Generic_Grass_Patch_01": "Grass",
    "SM_Env_Dirt_Rows_Center_01": "Center",
    "SM_Env_Dirt_Rows_End_Top_01": "End",
    "SM_Env_Dirt_Skirt_01": "Skirt",
}


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def compact(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False)


def converted(v: list[float], scale: float = 1) -> list[float]:
    return [v[0] * scale, v[2] * scale, -v[1] * scale]


def indexed(values: list[list[float]]) -> tuple[list[list[float]], list[int]]:
    """Deduplicate identical channel triples/pairs without rounding floats."""
    table: list[list[float]] = []
    indices: list[int] = []
    lookup: dict[tuple[float, ...], int] = {}
    for value in values:
        token = tuple(value)
        if token not in lookup:
            lookup[token] = len(table) + 1
            table.append(value)
        indices.append(lookup[token])
    return table, indices


def main() -> None:
    intake_bytes = INTAKE.read_bytes()
    intake = json.loads(intake_bytes)
    corn = next(a for a in intake["assets"] if a["name"] == "SM_Prop_Plant_Corn_01_L")
    corn_height_m = max(v[2] for v in corn["vertices"]) - min(v[2] for v in corn["vertices"])
    scale = 8 / corn_height_m
    OUT.mkdir(parents=True, exist_ok=True)
    manifest: dict = {
        "schema": 1,
        "intake": str(INTAKE.relative_to(ROOT)).replace("\\", "/"),
        "intake_sha256": digest(intake_bytes),
        "axes": "Roblox [x,z,-y] from right-handed Blender world metres",
        "uniform_studs_per_metre": scale,
        "corn_height_metres": corn_height_m,
        "corn_height_studs": 8,
        "notes": "Exact float channel deduplication; unchanged triangle winding and corner assignments. No welding, normal recalculation, UV unwrap, source edits, or publication.",
        "geometry_module": "scene-c/geometry/Geometry.luau",
        "geometry_module_sha256": digest((ROOT / "scene-c/geometry/Geometry.luau").read_bytes()),
        "assets": [],
    }
    for asset in intake["assets"]:
        source = Path(asset["source"])
        assert digest(source.read_bytes()) == asset["source_sha256"], source
        positions = [converted(v, scale) for v in asset["vertices"]]
        low = [min(v[i] for v in positions) for i in range(3)]
        high = [max(v[i] for v in positions) for i in range(3)]
        center = [(a + b) / 2 for a, b in zip(low, high)]
        size = [b - a for a, b in zip(low, high)]
        entry = {
            "name": asset["name"],
            "source": str(source),
            "source_sha256": asset["source_sha256"],
            "vertices": len(positions),
            "triangles": len(asset["triangles"]),
            "size_studs": size,
            "source_center_studs": center,
        }
        if asset["name"] not in KEYS:
            assert asset is corn
            entry.update(key="Corn", mesh_uri="rbxassetid://104111861186519", texture_uri="rbxassetid://137803536172445")
            manifest["assets"].append(entry)
            continue
        key = KEYS[asset["name"]]
        triangles = asset["triangles"]
        all_uvs = [[uv[0], 1 - uv[1]] for t in triangles for uv in t["uv"]]
        all_normals = [converted(n) for t in triangles for n in t["normals"]]
        uvs, uv_indices = indexed(all_uvs)
        normals, normal_indices = indexed(all_normals)
        data = {
            "name": asset["name"],
            "key": key,
            "source_sha256": asset["source_sha256"],
            "uniform_studs_per_metre": scale,
            "source_center_studs": center,
            "bounds": {"min": [v - c for v, c in zip(low, center)], "max": [v - c for v, c in zip(high, center)], "size": size},
            "positions": [[n - c for n, c in zip(v, center)] for v in positions],
            "triangles": [[i + 1 for i in t["vertices"]] for t in triangles],
            "uvs": uvs,
            "normals": normals,
            "triangle_uvs": [uv_indices[i:i + 3] for i in range(0, len(uv_indices), 3)],
            "triangle_normals": [normal_indices[i:i + 3] for i in range(0, len(normal_indices), 3)],
            "texture_uri": "rbxassetid://95855894892409",
        }
        encoded = compact(data)
        assert "]==]" not in encoded
        body = (
            "-- Generated by scene-c/geometry/build-data.py; original FBX geometry and palette UVs.\n"
            f"-- FBX SHA-256: {asset['source_sha256']}\n"
            "return game:GetService(\"HttpService\"):JSONDecode(\n\t[==[" + encoded + "]==]\n)\n"
        ).encode("utf-8")
        assert len(body) < 200_000, (key, len(body))
        path = OUT / f"{key}.luau"
        path.write_bytes(body)
        entry.update(key=key, module=str(path.relative_to(ROOT)).replace("\\", "/"), module_bytes=len(body), module_sha256=digest(body), json_sha256=digest(encoded.encode("utf-8")), unique_uvs=len(uvs), unique_normals=len(normals))
        manifest["assets"].append(entry)
    (OUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(compact({"scale": scale, "assets": manifest["assets"]}))


if __name__ == "__main__":
    main()
