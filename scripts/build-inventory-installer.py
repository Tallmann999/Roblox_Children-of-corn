"""Build a guarded code-only farm update. No place files are rewritten."""
from pathlib import Path
import json
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
BASELINE_REV = '23d9e3503c37264593d3cef8e4cd4cd9256eeed7'
PREFIXES = ('ReplicatedStorage/GameShared', 'ServerScriptService/GameServer', 'StarterPlayer/StarterPlayerScripts/GameClient')
ADDITIONS = {'ReplicatedStorage/GameShared/Game/Inventory', 'ServerScriptService/GameServer/Game/ItemModels', 'ServerScriptService/GameServer/Game/InventoryWorld', 'StarterPlayer/StarterPlayerScripts/GameClient/Controllers/InventoryController', 'StarterPlayer/StarterPlayerScripts/GameClient/Game/InventoryHud', 'StarterPlayer/StarterPlayerScripts/GameClient/Controllers/CornWindController', 'ReplicatedStorage/GameShared/Game/FarmGeometryData/SM_Prop_Tyre_01', 'ReplicatedStorage/GameShared/Game/FarmEditableMeshBuilder', 'ServerScriptService/GameServer/Game/FarmGeometry', 'ReplicatedStorage/GameShared/Game/FarmGeometryData/SM_Bld_Barn_03', 'ReplicatedStorage/GameShared/Game/FarmGeometryData/SM_Prop_Rubbish_Pile_05', 'StarterPlayer/StarterPlayerScripts/GameClient/Controllers/CornAppearanceController', 'ReplicatedStorage/GameShared/Game/CornAppearance', 'StarterPlayer/StarterPlayerScripts/GameClient/Controllers/GateHintController', 'StarterPlayer/StarterPlayerScripts/GameClient/Controllers/FarmGeometryController', 'ServerScriptService/GameServer/Services/FarmGeometryService', 'ReplicatedStorage/GameShared/Game/ModePreviewImages', 'ReplicatedStorage/GameShared/Game/FarmGeometryData/SM_Prop_Truck_Rusted_01'}
mapping = {}
history_path = ROOT/'scripts/inventory-source-history.json'
history = json.loads((history_path if history_path.exists() else ROOT/'scripts/farm-source-history.json').read_text(encoding='utf-8'))
def visit_map(node, prefix=None):
    path = '' if prefix is None else (prefix+'/'+node['name'] if prefix else node['name'])
    files = [p for p in node.get('filePaths', []) if p.startswith('src/')]
    if files: mapping[path] = files[0]
    for child in node.get('children', []): visit_map(child, path)
visit_map(json.loads((ROOT/'build/sourcemap.json').read_text()))
CHUNK_PREFIX='ReplicatedStorage/GameShared/Game/FarmGeometryData/'
chunk_paths={path for path in mapping if path.startswith(CHUNK_PREFIX) and '/Chunk' in path}
assert chunk_paths, 'Generate protected farm data chunks before building installer'
ADDITIONS.update(chunk_paths)
for path in chunk_paths:
    assert len((ROOT/mapping[path]).read_text(encoding='utf-8').encode('utf-8')) < 200000, 'Source exceeds Studio limit'

rows = []
def visit(item, prefix=''):
    name = item.find("Properties/string[@name='Name']").text
    path = prefix+'/'+name if prefix else name
    source = item.find("Properties/*[@name='Source']")
    if source is not None and any(path.startswith(p+'/') for p in PREFIXES):
        assert (source.text or '').replace('\r\n','\n') == (ROOT/mapping[path]).read_text(encoding='utf-8').replace('\r\n','\n'), 'Build is stale; run scripts/check.ps1: '+path
        previous = subprocess.run(['git','show',BASELINE_REV+':'+mapping[path]], cwd=ROOT, capture_output=True)
        old = previous.stdout.decode('utf-8').replace('\r\n','\n') if previous.returncode == 0 else None
        assert old is not None or path in ADDITIONS, 'Unexpected missing baseline: '+path
        rows.append((path, item.attrib['class'], old, (source.text or '').replace('\r\n','\n')))
    for child in item.findall('Item'): visit(child, path)
for item in ET.parse(ROOT/'build/code-foundation.rbxlx').getroot().findall('Item'): visit(item)
assert len(rows) == 46+len(chunk_paths) and {p for p,_,old,_ in rows if old is None} == ADDITIONS
def literal(value):
    # Protect Source fingerprints from the limited Lune adapter's dot rewrites.
    return json.dumps(value, ensure_ascii=False).replace('.', r'\046')
table = '{\n'+',\n'.join('{path='+literal(p)+',allowMissing='+('true' if p in ADDITIONS else 'false')+',class='+literal(c)+',baseline='+('nil' if old is None else literal(old))+',history={'+','.join(literal(s) for s in history.get(p,[]))+'},source='+literal(new)+'}' for p,c,old,new in rows)+'\n}'
head = '''-- Generated by build-inventory-installer.py. Only Children_of_corn, stopped Edit mode.
local run=game:GetService("RunService")
assert(run:IsStudio() and not run:IsRunning(), "Stop Play before inventory code installation")
local world=game:GetService("Workspace")
assert(not world:FindFirstChild("Asmr_Base") and not world:FindFirstChild("ASMR_Models"), "Wrong game; nothing changed")
local map=world:FindFirstChild("CornMap")
assert(map and map:IsA("Model") and map:GetAttribute("corn_project_id")=="children_of_corn", "Open Children_of_corn; nothing changed")
local function resolve(path)
    local found=game
    for _,segment in string.split(path,"/") do found=found and found:FindFirstChild(segment) end
    return found
end
local function normalized(source) return (string.gsub(source,"\\r\\n","\\n")) end
local editor=game:GetService("ScriptEditorService")
local entries='''
tail = '''
local newDataPath="ReplicatedStorage/GameShared/Game/FarmGeometryData"
local dataFolder=resolve(newDataPath)
if dataFolder then assert(dataFolder:IsA("Folder"),"Farm data folder collision") end
for _,entry in entries do
    local item=resolve(entry.path)
    local parentPath=string.match(entry.path,"^(.*)/[^/]+$")
    assert(resolve(parentPath) or parentPath=="ReplicatedStorage/GameShared/Game/FarmGeometryData" or string.match(parentPath,"^ReplicatedStorage/GameShared/Game/FarmGeometryData/SM_[%w_]+$"),"Missing code parent; nothing changed: "..entry.path)
    if item then
        assert(item.ClassName==entry.class,"Object collision; nothing changed: "..entry.path)
        assert(editor:FindScriptDocument(item)==nil,"Close script tab; nothing changed: "..entry.path)
        local recognized=normalized(item.Source)==normalized(entry.source) or (entry.baseline and normalized(item.Source)==normalized(entry.baseline))
        for _,oldSource in entry.history do recognized=recognized or normalized(item.Source)==normalized(oldSource) end
        assert(recognized,"Manual Source edit; nothing changed: "..entry.path)
    else
        assert(entry.allowMissing==true and entry.baseline==nil and entry.class=="ModuleScript","Missing baseline code; nothing changed: "..entry.path)
    end
end
local allowed={}
for _,entry in entries do local item=resolve(entry.path);if item then allowed[item]=true end end
for _,path in {"ReplicatedStorage/GameShared","ServerScriptService/GameServer","StarterPlayer/StarterPlayerScripts/GameClient"} do
    for _,item in resolve(path):GetDescendants() do
        assert(not item:IsA("LuaSourceContainer") or allowed[item],"Unrecognized code; nothing changed: "..item:GetFullName())
    end
end
local history=game:GetService("ChangeHistoryService")
history:SetWaypoint("Before Corn inventory update")
local changed,created={},{}
local ok,problem=pcall(function()
    if not dataFolder then
        dataFolder=Instance.new("Folder"); dataFolder.Name="FarmGeometryData"
        table.insert(created,dataFolder); dataFolder.Parent=resolve("ReplicatedStorage/GameShared/Game")
    end
    for _,entry in entries do
        local item=resolve(entry.path)
        if not item then
            local parentPath,name=string.match(entry.path,"^(.*)/([^/]+)$")
            item=Instance.new(entry.class)
            item.Name=name
            table.insert(created,item)
            item.Source=entry.source
            item.Parent=resolve(parentPath)
        elseif normalized(item.Source)~=normalized(entry.source) then
            table.insert(changed,{item=item,source=item.Source})
            item.Source=entry.source
        end
    end
end)
if not ok then
    for _,entry in changed do entry.item.Source=entry.source end
    for index=#created,1,-1 do created[index]:Destroy() end
    error("Corn inventory update rolled back: "..tostring(problem))
end
history:SetWaypoint("Installed Corn inventory")
print("ChildrenOfCorn: inventory code installed; map and art preserved")
return {changed=#changed,created=#created}
'''
output = head+table+'\n'+tail
(ROOT/'scripts/install-inventory.luau').write_text(output, encoding='utf-8')
print('Built guarded farm installer:',len(rows),'sources; no place writes')

for path,_,_,source in rows:
    history.setdefault(path,[])
    if source not in history[path]: history[path].append(source)
history_path.write_text(json.dumps(history,ensure_ascii=False,indent=2),encoding="utf-8")
