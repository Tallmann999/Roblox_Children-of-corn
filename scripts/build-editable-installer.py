"""Generate the guarded Studio Command Bar installer; never writes a place file."""
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
LUNE = ROOT / '.tools/lune/lune.exe'
BACKUP = ROOT / 'place/Children_of_corn.before-editable.rbxl'
result = subprocess.run([str(LUNE), 'run', str(ROOT/'scripts/export-known-place.luau'), str(BACKUP)], capture_output=True, check=True)
original = ET.fromstring(result.stdout[result.stdout.index(b'<roblox '):])
updated = ET.parse(ROOT/'build/code-foundation.rbxlx').getroot()
PREFIXES = ('ReplicatedStorage/GameShared', 'ServerScriptService/GameServer', 'StarterPlayer/StarterPlayerScripts/GameClient')

def literal(value):
    assert ']========]' not in value
    return '[========['+value+']========]'

def entries(xml):
    rows = []
    def visit(item, prefix):
        name = item.find("Properties/string[@name='Name']").text
        path = prefix+'/'+name if prefix else name
        if any(path == p or path.startswith(p+'/') for p in PREFIXES):
            source = item.find("Properties/*[@name='Source']")
            rows.append((path, item.attrib['class'], None if source is None else source.text or ''))
        for child in item.findall('Item'):
            visit(child,path)
    for item in xml.findall('Item'):
        visit(item,'')
    return rows

def table(rows):
    return '{\n'+',\n'.join('{ path = '+literal(path)+', class = '+literal(cls)+('' if source is None else ', source = '+literal(source.replace('\r\n','\n')))+' }' for path,cls,source in rows)+'\n}'

old = entries(original)
new = entries(updated)
assert sum(s is not None for _,_,s in old) == 15
assert sum(s is not None for _,_,s in new) == 20
head = '''-- Generated by scripts/build-editable-installer.py. Paste ALL into Studio Command Bar.
-- Target: place/Children_of_corn.rbxl; only run while the test is stopped.
local run = game:GetService("RunService")
assert(run:IsStudio() and not run:IsRunning(), "Stop Play and use Studio Edit mode")
local world = game:GetService("Workspace")
assert(not world:FindFirstChild("Asmr_Base") and not world:FindFirstChild("ASMR_Models"),
    "Speed Monkey detected; Corn installation refused before any changes")
local oldMap = world:FindFirstChild("CornMap")
if oldMap then
    assert(oldMap:IsA("Model") and oldMap:GetAttribute("corn_project_id") == "children_of_corn",
        "Unrecognized CornMap; nothing changed")
    print("ChildrenOfCorn: CornMap already installed; manual edits retained")
    return
end
local function resolve(path)
    local found = game
    for _, segment in string.split(path, "/") do found = found and found:FindFirstChild(segment) end
    return found
end
local function normalized(source) return (string.gsub(source, "\\r\\n", "\\n")) end
local editor = game:GetService("ScriptEditorService")
local function requireClosed(item)
    assert(editor:FindScriptDocument(item) == nil,
        "Close this script tab before installation: " .. item:GetFullName() .. "; nothing changed")
end
local config = resolve("ReplicatedStorage/GameShared/Config/GameConfig")
if config and config:IsA("LuaSourceContainer") then requireClosed(config) end
assert(config and config:IsA("ModuleScript") and string.find(config.Source, 'Id = "children_of_corn"', 1, true),
    "Open Children_of_corn.rbxl; nothing changed")
local art = game:GetService("ServerStorage")
assert(art:FindFirstChild("CornPlantTemplate") or art:FindFirstChild("SM_Prop_Plant_Corn_01_L"),
    "Corn art missing; nothing changed")
local baseline = '''
tail = '''
local previous = {}
for _, entry in baseline do
    local found = resolve(entry.path)
    assert(found and found.ClassName == entry.class, "Baseline mismatch: " .. entry.path .. "; nothing changed")
    if entry.source then
        requireClosed(found)
        assert(normalized(found.Source) == normalized(entry.source),
            "Source changed: " .. entry.path .. "; nothing changed")
    end
    previous[entry.path] = found
end
for _, entry in updates do
    local found = resolve(entry.path)
    if found then
        assert(found.ClassName == entry.class, "Object collision: " .. entry.path .. "; nothing changed")
        if entry.source then requireClosed(found) end
        if entry.source and not previous[entry.path] then
            assert(normalized(found.Source) == normalized(entry.source), "New module collision: " .. entry.path)
        end
    end
end
local obsolete = resolve("ServerScriptService/GameServer/Game/GreyboxWorld")
assert(not obsolete or #obsolete:GetChildren() == 0,
    "GreyboxWorld contains extra objects; nothing changed")
local obsoleteParent = obsolete and obsolete.Parent
local history = game:GetService("ChangeHistoryService")
history:SetWaypoint("Before editable Corn scene")
local created = {}
local changed = {}
local newMap = nil
local ok, problem = pcall(function()
    for _, entry in updates do
        local found = resolve(entry.path)
        if not found then
            local parentPath, name = string.match(entry.path, "^(.*)/([^/]+)$")
            local parent = assert(resolve(parentPath), "Missing code parent")
            found = Instance.new(entry.class)
            found.Name = name
            found.Parent = parent
            table.insert(created, found)
        end
        if entry.source then
            table.insert(changed, { item = found, source = found.Source })
            found.Source = entry.source
        end
    end
    if obsolete then obsolete.Parent = nil end
    newMap = require(resolve("ServerScriptService/GameServer/Game/MapAuthoring")).Install()
end)
if not ok then
    if newMap then newMap:Destroy() end
    if obsolete then obsolete.Parent = obsoleteParent end
    for _, entry in changed do entry.item.Source = entry.source end
    for index = #created, 1, -1 do created[index]:Destroy() end
    error("Corn installation rolled back: " .. tostring(problem))
end
if obsolete then obsolete:Destroy() end
history:SetWaypoint("Installed editable Corn scene")
print("ChildrenOfCorn editable scene installed: 1200 x 1200; SAVE this Corn scene, then Play")
'''
output = head+table(old)+'\nlocal updates = '+table(new)+'\n'+tail
path = ROOT/'scripts/install-editable-scene.luau'
path.write_text(output,encoding='utf-8')
print(f'Built {path.name}: {len(output.encode())} bytes, 20 scripts; no place files written')
