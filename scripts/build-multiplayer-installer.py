"""Build exact-baseline/final-state multiplayer installer; no scene write or sync."""
import argparse
import hashlib
import importlib.util
import json
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("multiplayer_pipeline", ROOT / "scripts/verify-multiplayer-copy.py")
v = importlib.util.module_from_spec(spec)
spec.loader.exec_module(v)
require = v.require


def digest(source):
    return hashlib.sha256(source.replace("\r\n", "\n").encode("utf-8")).hexdigest()


def literal(value):
    # Luau decimal escapes prevent a module path or Source from acting as code.
    return json.dumps(value, ensure_ascii=False).replace(".", r"\046")


def build():
    require(v.BASELINE.stat().st_size == v.BASELINE_BYTES and v.sha256(v.BASELINE) == v.BASELINE_HASH, "Immutable before-multiplayer baseline changed")
    before, _ = v.r.p.known_dom(v.BASELINE)
    old = {path: node["properties"]["Source"][1].replace("\r\n", "\n") for path, node in before.items() if "Source" in node["properties"]}
    require(len(before) == v.BASELINE_INSTANCES and len(old) == 78, "Unexpected immutable baseline topology")
    sources, classes = v.mapping_from_sourcemap(ROOT / "build/sourcemap.json")
    assets = v.fog.current_sources()
    require(set(sources | assets) == set(old) | v.ADDITIONS, "Unexpected final Source topology")
    require(set(classes) == {p for p in before if v.r.p.owned(p)} | v.ADDITIONS, "Unexpected new/missing code container")
    require(all(classes[p] == before[p]["class"] for p in classes if p in before), "Original code class changed")
    require(all(classes[p] == "ModuleScript" for p in v.ADDITIONS), "Additions must be ModuleScripts")
    changed = {p for p in old if (sources | assets)[p] != old[p]}
    require(changed.issubset(v.DECLARED_SOURCES), "Undeclared Source changes: " + str(sorted(changed - v.DECLARED_SOURCES)))
    built = {}
    def visit(item, prefix=""):
        name = item.find("Properties/string[@name='Name']").text
        path = prefix + "/" + name if prefix else name
        source = item.find("Properties/*[@name='Source']")
        if source is not None:
            require(path not in built and path in sources and item.attrib["class"] == classes[path], "Unexpected/duplicate built Source: " + path)
            value = (source.text or "").replace("\r\n", "\n")
            require(value == sources[path], "Stale build: run check.ps1: " + path)
            require(len(value.encode("utf-8")) < 200000, "Studio Source limit exceeded: " + path)
            built[path] = value
        for child in item.findall("Item"):
            visit(child, path)
    for item in ET.parse(ROOT / "build/code-foundation.rbxlx").getroot().findall("Item"):
        visit(item)
    require(built == sources, "Missing built project Sources")
    entries = []
    for path, source in sorted((sources | assets).items()):
        original = old.get(path)
        entries.append("{path=" + literal(path) + ",class=" + literal(classes.get(path, before[path]["class"] if path in before else "ModuleScript")) +
            ",before=" + (literal(digest(original)) if original is not None else "nil") + ",after=" + literal(digest(source)) +
            ",source=" + (literal(source) if original != source else "nil") + "}")
    expected = "{" + ",".join("[" + literal(path) + "]=" + literal(cls) for path, cls in sorted(classes.items())) + "}"
    source = '''-- Generated by build-multiplayer-installer.py. Children_of_corn stopped Edit only.
-- Immutable before-multiplayer SHA256: ''' + v.BASELINE_HASH + '''
local run=game:GetService("RunService")
assert(run:IsStudio() and run:IsEdit() and not run:IsRunning(),"Stop Play before multiplayer code installation")
local world=game:GetService("Workspace")
assert(not world:FindFirstChild("Asmr_Base") and not world:FindFirstChild("ASMR_Models"),"Wrong game; nothing changed")
local map=world:FindFirstChild("CornMap")
assert(map and map:IsA("Model") and map:GetAttribute("corn_project_id")=="children_of_corn","Open Children_of_corn; nothing changed")
local ground=map:FindFirstChild("Ground")
local field=map:FindFirstChild("FieldZone")
assert(ground and ground:IsA("BasePart") and ground.Size==Vector3.new(630,2,630),"Expected accepted 630 Ground; nothing changed")
assert(field and field:IsA("BasePart") and field.Size==Vector3.new(630,10,630),"Expected accepted 630 FieldZone; nothing changed")
assert(not map:FindFirstChild("Runtime"),"Runtime world exists; nothing changed")
local function uniqueChild(parent,name)
    local result=nil
    for _,child in parent:GetChildren() do
        if child.Name==name then assert(not result,"Duplicate instance name; nothing changed: "..name) result=child end
    end
    return result
end
local function resolve(path)
    local found=game
    for _,segment in string.split(path,"/") do found=found and uniqueChild(found,segment) end
    return found
end
local function pathOf(item)
    local names={}
    while item and item~=game do table.insert(names,1,item.Name) item=item.Parent end
    assert(item==game,"Detached instance; nothing changed")
    return table.concat(names,"/")
end
local function normalized(value) return (string.gsub(value,"\\r\\n","\\n")) end
local encoding=game:GetService("EncodingService")
local function digest(value)
    local raw=encoding:ComputeStringHash(normalized(value),Enum.HashAlgorithm.Sha256)
    return (string.gsub(raw,".",function(byte) return string.format("%02x",string.byte(byte)) end))
end
local editor=game:GetService("ScriptEditorService")
local entries={
''' + ",\n".join(entries) + '''
}
local expectedClasses=''' + expected + '''
local additions={''' + ",".join("[" + literal(p) + "]=true" for p in sorted(v.ADDITIONS)) + '''}
local byPath={}
local baseline,final=true,true
for _,entry in entries do
    byPath[entry.path]=entry
    local item=resolve(entry.path)
    if item then
        assert(item.ClassName==entry.class,"Source class collision; nothing changed: "..entry.path)
        assert(editor:FindScriptDocument(item)==nil,"Close script tab; nothing changed: "..entry.path)
        local hash=digest(item.Source)
        baseline=baseline and entry.before~=nil and hash==entry.before
        final=final and hash==entry.after
    else
        assert(additions[entry.path],"Missing original Source; nothing changed: "..entry.path)
        final=false
    end
    assert(not entry.source or digest(entry.source)==entry.after,"Installer Source/hash mismatch; nothing changed: "..entry.path)
end
assert(baseline or final,"Unknown Source edits or partial multiplayer install; nothing changed")
for path,cls in expectedClasses do
    local item=resolve(path)
    assert(item or (baseline and additions[path]),"Missing original code; nothing changed: "..path)
    assert(not item or item.ClassName==cls,"Code class collision; nothing changed: "..path)
end
for _,prefix in {"ReplicatedStorage/GameShared","ServerScriptService/GameServer","StarterPlayer/StarterPlayerScripts/GameClient"} do
    for _,item in resolve(prefix):GetDescendants() do
        local path=pathOf(item)
        assert(expectedClasses[path]==item.ClassName and resolve(path)==item,"Unexpected code topology; nothing changed: "..path)
    end
end
local sourceCount=0
for _,item in game:GetDescendants() do
    if item:IsA("LuaSourceContainer") then
        local path=pathOf(item)
        assert(byPath[path] and resolve(path)==item,"Unexpected persistent Source; nothing changed: "..path)
        sourceCount+=1
    end
end
assert(sourceCount==(if baseline then 78 else 80),"Persistent Source count differs; nothing changed")
if final then return {changed=0,created=0,sources=77,totalSources=80,repeated=true} end
local history=game:GetService("ChangeHistoryService")
history:SetWaypoint("Before Corn shared-key multiplayer")
local changed,created={},{}
local ok,problem=pcall(function()
    for _,entry in entries do
        local item=resolve(entry.path)
        if additions[entry.path] then
            assert(not item,"Added Source appeared; update rolled back: "..entry.path)
            item=Instance.new("ModuleScript")
            table.insert(created,item)
            item.Name=string.match(entry.path,"[^/]+$")
            item.Source=assert(entry.source)
            item.Parent=assert(resolve(string.match(entry.path,"^(.*)/[^/]+$")))
        elseif entry.source then
            assert(item and digest(item.Source)==entry.before,"Original Source changed; update rolled back: "..entry.path)
            table.insert(changed,{item=item,source=item.Source})
            item.Source=entry.source
        end
    end
    for _,entry in entries do
        local item=resolve(entry.path)
        assert(item and digest(item.Source)==entry.after,"Final Source verification failed; update rolled back: "..entry.path)
    end
end)
if not ok then
    for index=#changed,1,-1 do changed[index].item.Source=changed[index].source end
    for index=#created,1,-1 do created[index]:Destroy() end
    error("Multiplayer update rolled back: "..tostring(problem))
end
history:SetWaypoint("Installed Corn shared-key multiplayer")
print("ChildrenOfCorn: shared-key multiplayer code installed; author world and art preserved")
return {changed=#changed,created=#created,sources=77,totalSources=80,repeated=false}
'''
    output = ROOT / "scripts/install-multiplayer.luau"
    output.write_text(source, encoding="utf-8")
    require(v.sha256(v.BASELINE) == v.BASELINE_HASH, "Immutable baseline changed during build")
    print(json.dumps({"built": str(output), "sources": len(sources), "asset_sources": len(assets), "new_sources": len(v.ADDITIONS), "changed_existing_sources": sorted(changed), "bytes": output.stat().st_size, "compact_sha256_guards": True, "scene_written": False}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compact", action="store_true", help="Accepted for workflow compatibility; this installer always uses native SHA256 guards")
    parser.parse_args()
    build()
